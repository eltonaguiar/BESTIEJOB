#!/usr/bin/env python3
"""Normalize and score partner search results, then merge into pipeline."""
import sys
import json
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "scripts"))

from ai_scan_pipeline import (
    normalize_job, score_jobs_with_ai, local_ollama_chat,
    write_inbox_file, write_raw_results, run_merge_and_build,
    KEYS, TODAY, STAMP
)

def main():
    raw_file = ROOT / "scan_results" / f"{TODAY}_partner_raw.json"
    if not raw_file.exists():
        print(f"Raw file not found: {raw_file}")
        return
    
    raw = json.loads(raw_file.read_text(encoding="utf-8"))
    print(f"Raw results: {len(raw)}")
    
    # Normalize
    jobs = []
    seen = set()
    for r in raw:
        j = normalize_job(r, tier=4)
        if j and j["url"] not in seen:
            seen.add(j["url"])
            jobs.append(j)
    
    print(f"Normalized unique jobs: {len(jobs)}")
    
    if not jobs:
        print("No jobs to score.")
        return
    
    # Score with Ollama
    voters = [("ollama-qwen7b", local_ollama_chat, {"model": "qwen2.5:7b-instruct-q5_K_M"})]
    scored = score_jobs_with_ai(jobs, 4, voters=voters)
    scored.sort(key=lambda j: j.get("ai_score", 0), reverse=True)
    
    high = [j for j in scored if j.get("ai_score", 0) >= 7]
    print(f"Scored: {len(scored)} jobs, {len(high)} at 7+/10")
    
    # Print top 30
    print("\n=== TOP PARTNER JOBS ===")
    for j in scored[:30]:
        print(f"  {j.get('ai_score', 0)}/10 | {j.get('title','')[:60]} | {j.get('company','')} | {j.get('location','')} | {j.get('url','')[:70]}")
    
    # Save scored results
    out_dir = ROOT / "scan_results"
    out_file = out_dir / f"{TODAY}_partner_scored.json"
    out_file.write_text(json.dumps(scored, indent=2), encoding="utf-8")
    print(f"\nSaved scored results to {out_file}")
    
    # Write inbox file
    inbox_dir = ROOT / "inbox"
    inbox_dir.mkdir(exist_ok=True)
    existing = list(inbox_dir.glob(f"ai-scan--{TODAY}--v*.md"))
    v = len(existing) + 1
    inbox_file = inbox_dir / f"ai-scan--{TODAY}--v{v}.md"
    
    lines = [f"# AI Scan — {TODAY} (Partner Search v{v})", ""]
    lines.append("Generated by scripts/partner_search.py — ServiceNow partner company job search")
    lines.append("")
    lines.append("| Posted | Role | Company | Location | Score | AI Reason | URL |")
    lines.append("|---|---|---|---|---|---|---|")
    for j in scored:
        posted = j.get("postedDate", TODAY)[:10]
        score = j.get("ai_score", 0)
        reason = j.get("ai_reason", "")[:80].replace("|", "\\|")
        lines.append(f"| {posted} | [{j['title']}]({j['url']}) | {j['company']} | {j['location']} | {score}/10 | {reason} | {j['url']} |")
    lines.append("")
    lines.append(f"_Partner search · {len(scored)} jobs · Generated {STAMP}_")
    inbox_file.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Inbox written to {inbox_file}")
    
    # Run merge + build
    print("\n=== MERGE + BUILD ===")
    run_merge_and_build()

if __name__ == "__main__":
    main()
