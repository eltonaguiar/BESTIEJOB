#!/usr/bin/env python3
"""regenerate_fresh_jobs.py — rebuild FRESH_JOBS.md from jobs.json."""

import json
import re
from collections import defaultdict
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
JOBS_PATH = ROOT / "jobs.json"
OUT_PATH = ROOT / "FRESH_JOBS.md"

TAG_LABELS = {
    "servicenow": "ServiceNow",
    "salesforce": "Salesforce",
    "vba": "VBA / Excel automation",
    "alteryx": "Alteryx",
    "full-stack": "Full stack",
    "data": "Data / BI",
    "devops": "DevOps / Cloud",
    "python": "Python",
    "it-reporting": "IT Reporting",
    "itam": "IT Asset Mgmt / CMDB",
}

# Order of sections (primary first, then secondary)
SECTION_ORDER = [
    "servicenow", "salesforce",
    "vba", "alteryx", "full-stack", "data", "devops", "python",
    "it-reporting", "itam",
]


def fmt_date(iso: str) -> str:
    if not iso:
        return "—"
    try:
        return iso[:10]
    except Exception:
        return "—"


def cell(text: str) -> str:
    return (text or "").replace("|", "/").replace("\n", " ").strip()


def main():
    data = json.loads(JOBS_PATH.read_text(encoding="utf-8"))
    jobs = data.get("jobs", [])
    meta = data.get("meta", {})

    # Group jobs by tag
    by_tag: dict[str, list[dict]] = defaultdict(list)
    for j in jobs:
        tags = j.get("tags", []) or []
        if not tags:
            tags = ["other"]
        for tag in tags:
            by_tag[tag].append(j)

    # Build source counts
    source_counts: dict[str, int] = defaultdict(int)
    for j in jobs:
        source_counts[j.get("source", "unknown")] += 1

    total = len(jobs)

    lines = []
    lines.append("# Fresh job scan")
    lines.append("")
    stamp = datetime.now(timezone.utc).isoformat()
    lines.append(f"Auto-generated by `tools/regenerate_fresh_jobs.py` on {stamp}. Every row is a live posting pulled from an employer ATS or public job feed during this scan — newest first.")
    lines.append("")
    lines.append(f"**{total} matching postings** across {len(source_counts)} sources:")
    lines.append("")
    for src in sorted(source_counts, key=lambda s: -source_counts[s]):
        lines.append(f"- {src}: {source_counts[src]}")
    lines.append("")

    # Generate sections
    for tag in SECTION_ORDER:
        tag_jobs = by_tag.get(tag, [])
        if not tag_jobs:
            continue
        label = TAG_LABELS.get(tag, tag.title())
        lines.append(f"## {label} ({len(tag_jobs)})")
        lines.append("")
        lines.append("| Posted | Role | Company | Location | Type | Source |")
        lines.append("|---|---|---|---|---|---|")

        # Sort by postedDate descending
        sorted_jobs = sorted(tag_jobs, key=lambda j: j.get("postedDate", ""), reverse=True)
        for j in sorted_jobs:
            title = cell(j.get("title", ""))
            url = j.get("url", "")
            company = cell(j.get("company", ""))
            location = cell(j.get("location", ""))
            etype = cell(j.get("employmentType", "unknown"))
            source = cell(j.get("source", "unknown"))
            posted = fmt_date(j.get("postedDate", ""))
            lines.append(f"| {posted} | [{title}]({url}) | {company} | {location} | {etype} | {source} |")
        lines.append("")

    # Scan notes
    lines.append("## Scan notes")
    lines.append("")
    lines.append("- Jobs tagged with multiple categories appear in each matching section.")
    lines.append("- Exa search results (rounds 1-30) merged via `tools/normalize_exa_rounds.py`.")
    lines.append("- Undated postings show an em dash; dates come from the source page.")
    lines.append("")

    OUT_PATH.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {OUT_PATH} — {total} jobs, {len(by_tag)} tag sections")
    for tag in SECTION_ORDER:
        n = len(by_tag.get(tag, []))
        if n:
            print(f"  {TAG_LABELS.get(tag, tag)}: {n}")


if __name__ == "__main__":
    main()
